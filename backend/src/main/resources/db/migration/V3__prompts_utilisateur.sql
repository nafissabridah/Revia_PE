-- Bibliothèque de prompts personnels (réutilisables depuis l'écran Assistant IA)

CREATE TABLE prompt_utilisateur (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT       NOT NULL,
    titre          VARCHAR(80)  NOT NULL,
    contenu        VARCHAR(4000) NOT NULL,
    cree_le        TIMESTAMP    NOT NULL,
    modifie_le     TIMESTAMP    NOT NULL,
    CONSTRAINT fk_prompt_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE
);

CREATE INDEX ix_prompt_utilisateur_auteur ON prompt_utilisateur (utilisateur_id, titre);
