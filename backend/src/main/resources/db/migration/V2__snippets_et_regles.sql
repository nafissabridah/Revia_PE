-- Bibliothèque de snippets et règles de revue personnalisées (CRUD par utilisateur)

CREATE TABLE snippet (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  BIGINT       NOT NULL,
    titre           VARCHAR(120) NOT NULL,
    langage         VARCHAR(30)  NOT NULL,
    tags            VARCHAR(200),
    code            TEXT         NOT NULL,
    cree_le         TIMESTAMP    NOT NULL,
    modifie_le      TIMESTAMP    NOT NULL,
    CONSTRAINT fk_snippet_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE
);
CREATE INDEX idx_snippet_utilisateur ON snippet (utilisateur_id);

CREATE TABLE regle_revue (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  BIGINT       NOT NULL,
    nom             VARCHAR(120) NOT NULL,
    description     VARCHAR(500),
    gravite         VARCHAR(20)  NOT NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    cree_le         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_regle_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE,
    CONSTRAINT ck_regle_gravite CHECK (gravite IN ('CRITIQUE', 'MAJEURE', 'MINEURE', 'INFO'))
);
CREATE INDEX idx_regle_utilisateur ON regle_revue (utilisateur_id);
