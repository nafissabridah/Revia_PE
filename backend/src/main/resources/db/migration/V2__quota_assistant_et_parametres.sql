-- Quota journalier de l'assistant IA / outils IA, historique d'usage et paramètres modifiables par l'administrateur

ALTER TABLE utilisateur ADD COLUMN quota_assistant INTEGER NOT NULL DEFAULT 100;

CREATE TABLE usage_assistant (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT      NOT NULL,
    outil          VARCHAR(20) NOT NULL,
    cree_le        TIMESTAMP   NOT NULL,
    CONSTRAINT fk_usage_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE
);

CREATE INDEX ix_usage_utilisateur_date ON usage_assistant (utilisateur_id, cree_le);

CREATE TABLE parametre (
    cle    VARCHAR(40)  PRIMARY KEY,
    valeur VARCHAR(100) NOT NULL
);
